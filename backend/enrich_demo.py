def main():
    print("Loading existing embeddings...")
    with open(EMBEDDINGS_FILE, "r", encoding="utf-8") as f:
        existing = json.load(f)

    # Remove old demo/aswan chunks
    remove_ids = {c["id"] for c in DEMO_CHUNKS}
    remove_ids.update({"aswan_01","aswan_02","aswan_03","aswan_04"})  # old enrichment
    existing = [c for c in existing if c.get("id") not in remove_ids]

    total = len(DEMO_CHUNKS)
    print(f"Embedding {total} demo chunks (with rate-limit pauses)...")
    for i, chunk in enumerate(DEMO_CHUNKS):
        print(f"  [{i+1}/{total}] {chunk['id']}...")
        res = genai.embed_content(
            model="models/gemini-embedding-001",
            content=chunk["text"],
            task_type="retrieval_document"
        )
        ec = chunk.copy()
        ec["embedding"] = res["embedding"]
        existing.append(ec)
        time.sleep(3)  # generous pause

    print("Saving embeddings.json...")
    with open(EMBEDDINGS_FILE, "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)

    print("Saving chunks.json...")
    chunks_only = [{k:v for k,v in c.items() if k != "embedding"} for c in existing]
    with open(CHUNKS_FILE, "w", encoding="utf-8") as f:
        json.dump(chunks_only, f, ensure_ascii=False, indent=2)

    print("Done! RAG enriched with demo-ready Aswan data + local images.")

if __name__ == "__main__":
    main()
