def get_persona(monument_name):
    monument_clean = monument_name.replace("#", "").strip()
    for key in PERSONAS:
        key_words = key.split("—")[0].strip()
        if any(word in monument_clean for word in key_words.split() if len(word) > 2):
            return PERSONAS[key], key
    return None, monument_clean

def cosine_similarity(a, b):
    a, b = np.array(a), np.array(b)
    return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))

def search(query, top_k=4):
    response = client.models.embed_content(
        model="gemini-embedding-001",
        contents=query
    )
    query_vec = response.embeddings[0].values
    scored = []
    for chunk in data:
        score = cosine_similarity(query_vec, chunk["embedding"])
        scored.append((score, chunk))
    scored.sort(key=lambda x: x[0], reverse=True)
    return scored[:top_k]

def ask_character(question, chunks):
    context = ""
    monument = chunks[0][1]["monument"].replace("#", "").strip()
    builder = chunks[0][1]["builder"].strip()

    for score, chunk in chunks:
        context += f"\n---\n{chunk['text'][:800]}"

    persona, persona_key = get_persona(monument)

    if persona:
        persona_instructions = f"""
النبرة: {persona['نبرة']}
اللغة: {persona['لغة']}
مفردات مناسبة: {persona['مفردات']}
عند عدم المعرفة قل: "{persona['عند_عدم_المعرفة']}"
مثال على أسلوبك: "{persona['مثال']}"
تجنب: {persona['تجنب']}
"""
    else:
        persona_instructions = "تكلم بعربية فصحى مناسبة لعصرك وشخصيتك."

    prompt = f"""أنت شخصية تاريخية من {monument}.
اسمك أو دورك: {builder}.

تعليمات الشخصية:
{persona_instructions}

قواعد صارمة:
- رد بالعربية فقط
- استخدم فقط المعلومات الموجودة في النص المرجعي التالي
- لا تخترع معلومات غير موجودة في النص
- تكلم بضمير المتكلم كشخصية حقيقية
- لا تتكلم كمرشد سياحي أو موسوعة
- اكتب فقرتين واضحتين، لا أكثر ولا أقل
- كل فقرة من 3 إلى 4 جمل
- كل جملة لا تتجاوز 14 كلمة تقريبًا، وتحمل فكرة واحدة فقط
- لا تحشو الجملة الواحدة بأكثر من معلومة أو تاريخ أو رقم
- الرد كله يجب أن يكون بين 90 و120 كلمة تقريبًا

النص المرجعي:
{context}

سؤال الزائر: {question}

ردك كشخصية (فقرتين واضحتين، جمل قصيرة ومباشرة):"""

    response = client.models.generate_content(
        model="gemini-2.5-flash",
        contents=prompt,
        config=types.GenerateContentConfig(
            max_output_tokens=320,
            thinking_config=types.ThinkingConfig(thinking_budget=0)
        )
    )
    return response.text, monument, builder

@app.route("/ask", methods=["POST"])
def ask():
    question = request.json.get("question", "")
    if not question:
        return jsonify({"error": "سؤال فاضي"}), 400

    results = search(question)
    answer, monument, builder = ask_character(question, results)

    return jsonify({
        "answer": answer,
        "monument": monument,
        "builder": builder
    })

