def get_persona(monument_name):
    """Match monument name to persona."""
    monument_clean = monument_name.replace("#", "").strip()
    for key in PERSONAS:
        # Check if key words match
        key_words = key.split("—")[0].strip()
        if any(word in monument_clean for word in key_words.split() if len(word) > 2):
            return PERSONAS[key], key
    return None, monument_clean

def cosine_similarity(a, b):
    a, b = np.array(a), np.array(b)
    return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))

def search(query, top_k=4):
    response = client.models.embed_content(
        model="gemini-embedding-001",
        contents=query
    )
    query_vec = response.embeddings[0].values

    scored = []
    for chunk in data:
        score = cosine_similarity(query_vec, chunk["embedding"])
        scored.append((score, chunk))

    scored.sort(key=lambda x: x[0], reverse=True)
    return scored[:top_k]

